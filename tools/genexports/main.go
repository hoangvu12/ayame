package main

import (
	"encoding/binary"
	"fmt"
	"os"
	"sort"
	"strings"
)

// readExports parses the export directory of a PE file and returns export names.
func readExports(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	if len(data) < 0x40 || string(data[0:2]) != "MZ" {
		return nil, fmt.Errorf("not a PE file")
	}
	peOff := int(binary.LittleEndian.Uint32(data[0x3c:]))
	if peOff+24 > len(data) || string(data[peOff:peOff+4]) != "PE\x00\x00" {
		return nil, fmt.Errorf("bad PE header")
	}
	// COFF header
	// Machine(2) NumberOfSections(2) TimeDateStamp(4) PtrSymTab(4) NumSym(2) SizeOptHdr(2) Char(2)
	sizeOpt := int(binary.LittleEndian.Uint16(data[peOff+20:]))
	optOff := peOff + 24
	if optOff+2 > len(data) {
		return nil, fmt.Errorf("bad optional header")
	}
	magic := binary.LittleEndian.Uint16(data[optOff:])
	var exportRVA uint32
	if magic == 0x20b { // PE32+
		// DataDirectory starts at optOff+112 for PE32+
		dd := optOff + 112
		exportRVA = binary.LittleEndian.Uint32(data[dd:])
	} else if magic == 0x10b { // PE32
		dd := optOff + 96
		exportRVA = binary.LittleEndian.Uint32(data[dd:])
	} else {
		return nil, fmt.Errorf("unknown optional magic %x", magic)
	}
	if exportRVA == 0 {
		return nil, fmt.Errorf("no export directory")
	}

	// Build section table for RVA->file-offset.
	numSec := int(binary.LittleEndian.Uint16(data[peOff+6:]))
	secOff := optOff + sizeOpt
	type section struct {
		vsize, vaddr, rsize, rptr uint32
	}
	var secs []section
	for i := 0; i < numSec; i++ {
		so := secOff + i*40
		if so+40 > len(data) {
			break
		}
		secs = append(secs, section{
			vsize: binary.LittleEndian.Uint32(data[so+8:]),
			vaddr: binary.LittleEndian.Uint32(data[so+12:]),
			rsize: binary.LittleEndian.Uint32(data[so+16:]),
			rptr:  binary.LittleEndian.Uint32(data[so+20:]),
		})
	}
	rvaToOff := func(rva uint32) (int, error) {
		for _, s := range secs {
			span := s.vsize
			if s.rsize > span {
				span = s.rsize
			}
			if rva >= s.vaddr && rva < s.vaddr+span {
				return int(rva - s.vaddr + s.rptr), nil
			}
		}
		return 0, fmt.Errorf("rva %x not mapped", rva)
	}

	expOff, err := rvaToOff(exportRVA)
	if err != nil {
		return nil, err
	}
	// IMAGE_EXPORT_DIRECTORY
	numNames := binary.LittleEndian.Uint32(data[expOff+24:])
	namesRVA := binary.LittleEndian.Uint32(data[expOff+32:])
	namesOff, err := rvaToOff(namesRVA)
	if err != nil {
		return nil, err
	}
	var names []string
	for i := uint32(0); i < numNames; i++ {
		nrva := binary.LittleEndian.Uint32(data[namesOff+int(i)*4:])
		noff, err := rvaToOff(nrva)
		if err != nil {
			continue
		}
		end := noff
		for end < len(data) && data[end] != 0 {
			end++
		}
		names = append(names, string(data[noff:end]))
	}
	sort.Strings(names)
	// de-dup
	out := names[:0]
	for i, n := range names {
		if i == 0 || n != names[i-1] {
			out = append(out, n)
		}
	}
	return out, nil
}

// readNamesFile reads a plain-text list of export names (one per line).
func readNamesFile(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(strings.TrimSuffix(line, "\r"))
		if line == "" || strings.HasPrefix(line, ";") || strings.HasPrefix(line, "#") {
			continue
		}
		out = append(out, line)
	}
	return out, nil
}

func main() {
	if len(os.Args) < 3 {
		fmt.Fprintln(os.Stderr, "usage: genexports <outdir> <dll-or-txt>... [-- intercept...]")
		os.Exit(1)
	}
	outdir := os.Args[1]
	intercept := map[string]bool{}
	seen := map[string]bool{}
	var names []string
	mode := "inputs"
	for _, arg := range os.Args[2:] {
		if arg == "--" {
			mode = "intercept"
			continue
		}
		if mode == "intercept" {
			intercept[arg] = true
			continue
		}
		var got []string
		var err error
		if strings.HasSuffix(strings.ToLower(arg), ".txt") {
			got, err = readNamesFile(arg)
		} else {
			got, err = readExports(arg)
		}
		if err != nil {
			fmt.Fprintf(os.Stderr, "warning: %s: %v\n", arg, err)
			continue
		}
		for _, n := range got {
			if !seen[n] {
				seen[n] = true
				names = append(names, n)
			}
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		fmt.Fprintln(os.Stderr, "no exports collected")
		os.Exit(1)
	}
	if err := os.MkdirAll(outdir, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	var asm strings.Builder
	var def strings.Builder
	var hdr strings.Builder

	asm.WriteString("; auto-generated by genexports; do not edit\n")
	asm.WriteString(".data\n")
	asm.WriteString("PUBLIC g_ayame_procs\n")

	// Count forwards to size the proc table.
	var forwards []string
	for _, n := range names {
		if !intercept[n] {
			forwards = append(forwards, n)
		}
	}
	asm.WriteString(fmt.Sprintf("g_ayame_procs QWORD %d DUP (0)\n\n", len(forwards)))
	asm.WriteString(".code\n")

	def.WriteString("EXPORTS\n")
	hdr.WriteString("// auto-generated by genexports; do not edit\n#pragma once\n")
	hdr.WriteString(fmt.Sprintf("#define AYAME_NUM_FORWARDS %d\n", len(forwards)))
	hdr.WriteString("static const char* ayame_forward_names[AYAME_NUM_FORWARDS] = {\n")

	for i, n := range forwards {
		stub := fmt.Sprintf("aym_fwd_%d", i)
		asm.WriteString(fmt.Sprintf("%s PROC\n  jmp QWORD PTR [g_ayame_procs + %d]\n%s ENDP\n", stub, i*8, stub))
		def.WriteString(fmt.Sprintf("  %s=%s\n", n, stub))
		hdr.WriteString(fmt.Sprintf("  \"%s\",\n", n))
	}
	// Intercepted names are provided by our C code under the same symbol name.
	for _, n := range names {
		if intercept[n] {
			def.WriteString(fmt.Sprintf("  %s\n", n))
		}
	}

	asm.WriteString("END\n")
	hdr.WriteString("};\n")

	mustWrite := func(name, content string) {
		if err := os.WriteFile(outdir+"/"+name, []byte(content), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	prefix := os.Getenv("AYAME_GEN_PREFIX") // e.g. "winmm_" for the loader build
	mustWrite(prefix+"fwd_stub.asm", asm.String())
	mustWrite(prefix+"exports.def", def.String())
	mustWrite(prefix+"exports.h", hdr.String())
	fmt.Printf("wrote %d forwards, %d intercepted, %d total exports\n", len(forwards), len(intercept), len(names))
}
